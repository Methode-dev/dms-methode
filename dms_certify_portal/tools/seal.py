# Entry points
# ---------------------------------------------------------------------------
def _needs_band(src_page, spec):
    """Whether this page has to give up a strip for the seal block."""
    if spec.band == 'scale':
        return True
    if spec.band == 'overlay':
        return False
    return not _corner_is_free(src_page, spec.qr_corner)


def seal(pdf_bytes, spec):
    """Return *pdf_bytes* stamped according to *spec*.

    The watermark, guilloche and microtext go on every page; the seal block is
    printed once, on the last page, which is where a reader looks for a
    signature.
    """
    source = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        out = pymupdf.open()
        try:
            last = source.page_count - 1
            for index in range(source.page_count):
                src_page = source[index]
                src_rect = src_page.rect
                page = out.new_page(width=src_rect.width, height=src_rect.height)
                band_top = None
                if index == last and _needs_band(src_page, spec):
                    band_top = src_rect.height - SEAL_BAND_H
                    target = pymupdf.Rect(0, 0, src_rect.width, band_top)
                else:
                    target = pymupdf.Rect(0, 0, src_rect.width, src_rect.height)
                # show_pdf_page embeds the source as a form XObject: vectors
                # stay vectors and the text stays selectable and searchable.
                page.show_pdf_page(target, source, index)

                if spec.guilloche:
                    _draw_guilloche(page, rgb(spec.watermark_color))
                _draw_watermark(page, spec)
                _draw_microtext(page, spec)
                if index == last:
                    _draw_seal_block(page, spec, band_top)
            return out.tobytes(deflate=True, garbage=3)
        finally:
            out.close()
    finally:
        source.close()


def render_page(pdf_bytes, page_number=0, dpi=110):
    """Rasterise one page to PNG bytes.

    Both the desk preview and the portal's copy of the document go through
    here. Rasterising rather than embedding the PDF is a deliberate choice for
    the public side: a PDF in a viewer carries its own save, print and text
    extraction, all of it outside the gate that decided the reader was allowed
    to see the page at all. A picture has none of that, and the reader's job —
    comparing what is on screen with the paper in their hand — needs nothing
    more.
    """
    document = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        if page_number >= document.page_count:
            return b''
        pixmap = document[page_number].get_pixmap(dpi=dpi)
        return pixmap.tobytes('png')
    finally:
        document.close()


def page_count(pdf_bytes):
    document = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        return document.page_count
    finally:
        document.close()


def locate(pdf_bytes, needles):
    """Where each of *needles* sits in the document.

    Returns ``[{'p': page_index, 'r': [x0, y0, x1, y1]}, ...]`` in the
    document's own coordinates. Measured once against a known document, so a
    later redaction blanks exactly where something was found rather than
    searching the page again for a string that may also appear elsewhere on it.
    """
    wanted = [str(value) for value in (needles or []) if value and str(value).strip()]
    if not wanted:
        return []
    boxes = []
    document = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        for index, page in enumerate(document):
            for needle in wanted:
                for rect in page.search_for(needle):
                    boxes.append({'p': index,
                                  'r': [round(value, 2) for value in rect]})
        return boxes
    finally:
        document.close()


def redact_boxes(pdf_bytes, boxes):
    """Remove whatever sits inside *boxes*.

    A real redaction — ``apply_redactions`` drops the glyphs from the content
    stream, so the text is not merely covered. Images and line art are left
    alone (``images=0, graphics=0``): a crew table's own rules touch the
    rectangles, and removing them would take the grid apart around the blanked
    cells.
    """
    if not boxes:
        return pdf_bytes
    by_page = {}
    for box in boxes:
        by_page.setdefault(box['p'], []).append(box['r'])

    document = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        for index, rects in by_page.items():
            if index >= document.page_count:
                continue
            page = document[index]
            for rect in rects:
                page.add_redact_annot(pymupdf.Rect(*rect), fill=REDACTION_FILL)
            page.apply_redactions(images=0, graphics=0, text=0)
        return document.tobytes(deflate=True, garbage=3)
    finally:
        document.close()


def redact(pdf_bytes, needles):
    """Locate and remove in one step, for callers that hold the values."""
    return redact_boxes(pdf_bytes, locate(pdf_bytes, needles))


def text_tokens(pdf_bytes):
    """Every word in the document, for checking what a redaction left behind."""
    document = pymupdf.open(stream=pdf_bytes, filetype='pdf')
    try:
        return [word[4] for page in document for word in page.get_text('words')]
    finally:
        document.close()
